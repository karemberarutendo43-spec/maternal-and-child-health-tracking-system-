  id INT AUTO_INCREMENT PRIMARY KEY,
  clinic_code VARCHAR(32) NOT NULL UNIQUE,
  clinic_name VARCHAR(255) NOT NULL,
  auth_code VARCHAR(64) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

