function mch_who_tables(): array
{
    static $cache = null;
    if (is_array($cache)) {
        return $cache;
    }

    $t = mch_who_table_texts();
    $cache = [
        'wfa' => [
            'M' => mch_parse_who_sft_table($t['wfa_boys_0_5']),
            'F' => mch_parse_who_sft_table($t['wfa_girls_0_5']),
        ],
        'lhfa_0_2' => [
            'M' => mch_parse_who_sft_table($t['lhfa_boys_0_2']),
            'F' => mch_parse_who_sft_table($t['lhfa_girls_0_2']),
        ],
        'lhfa_2_5' => [
            'M' => mch_parse_who_sft_table($t['lhfa_boys_2_5']),
            'F' => mch_parse_who_sft_table($t['lhfa_girls_2_5']),
        ],
    ];

    return $cache;
}

function mch_who_interpolate_table(array $table, float $age_months): ?array
{
    if (empty($table)) {
        return null;
    }

    if ($age_months < 0) {
        $age_months = 0;
    }

    $keys = array_keys($table);
    $min = (int)min($keys);
    $max = (int)max($keys);
    if ($age_months < $min) {
        $age_months = $min;
    } elseif ($age_months > $max) {
        $age_months = $max;
    }

    $lo = (int)floor($age_months);
    $hi = (int)ceil($age_months);
    if (!isset($table[$lo])) {
        for ($i = $lo; $i >= $min; $i--) {
            if (isset($table[$i])) {
                $lo = $i;
                break;
            }
        }
    }
    if (!isset($table[$hi])) {
        for ($i = $hi; $i <= $max; $i++) {
            if (isset($table[$i])) {
                $hi = $i;
                break;
            }
        }
    }

    $rowLo = $table[$lo] ?? null;
    $rowHi = $table[$hi] ?? null;
    if (!$rowLo || !$rowHi) {
        return $rowLo ?: $rowHi;
    }
    if ($lo === $hi) {
        return $rowLo;
    }

    $t = ($age_months - $lo) / ($hi - $lo);
    $out = [];
    foreach ($rowLo as $k => $vLo) {
        $vHi = $rowHi[$k] ?? $vLo;
        $out[$k] = (float)$vLo + ((float)$vHi - (float)$vLo) * $t;
    }
    return $out;
}

function mch_who_wfa_table(string $sex): array
{
    $sex = strtoupper(trim($sex));
    $tables = mch_who_tables();
    return $tables['wfa'][$sex] ?? [];
}

function mch_who_lhfa_table(string $sex): array
{
    static $merged = [];
    $sex = strtoupper(trim($sex));
    if ($sex === '' || !in_array($sex, ['M', 'F'], true)) {
        return [];
    }
    if (isset($merged[$sex])) {
        return $merged[$sex];
    }

    $tables = mch_who_tables();
    $t0 = $tables['lhfa_0_2'][$sex] ?? [];
    $t2 = $tables['lhfa_2_5'][$sex] ?? [];

    $out = [];
    foreach ($t0 as $m => $row) {
        $m = (int)$m;
        if ($m < 24) {
            $out[$m] = $row;
        }
    }
    foreach ($t2 as $m => $row) {
        $out[(int)$m] = $row;
    }

    ksort($out);
    $merged[$sex] = $out;
    return $out;
}

function mch_who_ref_wfa(string $sex, float $age_months): ?array
{
    $table = mch_who_wfa_table($sex);
    return mch_who_interpolate_table($table, $age_months);
}

function mch_who_ref_lhfa(string $sex, float $age_months): ?array
{
    $table = mch_who_lhfa_table($sex);
    return mch_who_interpolate_table($table, $age_months);
}

