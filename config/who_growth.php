function mch_normalize_baby_sex(string $gender): ?string
{
    $g = strtolower(trim($gender));
    if ($g === '') {
        return null;
    }
    if (in_array($g, ['m', 'male', 'boy'], true)) {
        return 'M';
    }
    if (in_array($g, ['f', 'female', 'girl'], true)) {
        return 'F';
    }
    return null;
}

function mch_growth_age_months(?string $dob, ?string $observed_date): ?float
{
    $dob = trim((string)$dob);
    $observed_date = trim((string)$observed_date);
    if ($dob === '' || $observed_date === '') {
        return null;
    }

    try {
        $dobDt = new DateTimeImmutable($dob);
        $obsDt = new DateTimeImmutable($observed_date);
    } catch (Exception $e) {
        return null;
    }

    $days = (int)$dobDt->diff($obsDt)->format('%r%a');
    if ($days < 0) {
        return null;
    }
    return $days / 30.4375;
}

function mch_who_zone(float $value, ?array $ref): string
{
    if (!$ref || !isset($ref['m3'], $ref['m2'])) {
        return 'unknown';
    }
    if ($value < (float)$ref['m3']) {
        return 'red';
    }
    if ($value < (float)$ref['m2']) {
        return 'orange';
    }
    return 'green';
}

function mch_who_zone_label(string $zone): string
{
    return match ($zone) {
        'green' => 'Good',
        'orange' => 'Danger',
        'red' => 'Very Dangerous',
        default => 'Unknown',
    };
}

function mch_who_zone_badge_classes(string $zone): string
{
    return match ($zone) {
        'green' => 'bg-emerald-100 text-emerald-700',
        'orange' => 'bg-amber-100 text-amber-800',
        'red' => 'bg-rose-100 text-rose-700',
        default => 'bg-slate-100 text-slate-700',
    };
}

function mch_parse_who_sft_table(string $text): array
{
    $rows = [];
    $lines = preg_split("/\\R/", $text) ?: [];
    foreach ($lines as $line) {
        $line = trim($line);
        if ($line === '') {
            continue;
        }

        if (preg_match('/^L\\d+@P\\d+(?:-1)?\\s*:\\s*(.+)$/', $line, $m)) {
            $line = trim($m[1]);
        }

        if (!preg_match_all('/-?\\d+(?:\\.\\d+)?/', $line, $m)) {
            continue;
        }

        $nums = $m[0];
        if (count($nums) < 10) {
            continue;
        }

        $month = (int)$nums[2];
        if ($month < 0 || $month > 60) {
            continue;
        }

        $vals = array_slice($nums, 3, 7);
        if (count($vals) < 7) {
            continue;
        }

        $rows[$month] = [
            'm3' => (float)$vals[0],
            'm2' => (float)$vals[1],
            'm1' => (float)$vals[2],
            'med' => (float)$vals[3],
            'p1' => (float)$vals[4],
            'p2' => (float)$vals[5],
            'p3' => (float)$vals[6],
        ];
    }

    ksort($rows);
    return $rows;
}

